// Rebuild after changing the retained coastline. This runs offline, never during gameplay.
import fs from 'node:fs';
import {Navigation} from '../public/navigation.js';
const raw=fs.readFileSync(new URL('../public/assets/land.json',import.meta.url),'utf8'),geo=JSON.parse(raw),nav=new Navigation(geo),seen=new Set(),components=[];
for(let y=0;y<nav.rows;y++)for(let x=0;x<nav.cols;x++){
 const id=y*nav.cols+x;if(seen.has(id)||!nav.waterNode(x,y,.09))continue;
 const component=[id];seen.add(id);
 for(let i=0;i<component.length;i++){const k=component[i],a={x:-179+(k%180)*2,y:-79+Math.floor(k/180)*2};for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
  const nx=(k%180+dx+180)%180,ny=Math.floor(k/180)+dy,nk=ny*180+nx;
  if(ny<0||ny>=80||seen.has(nk)||!nav.waterNode(nx,ny,.09))continue;
  const b={x:-179+nx*2,y:-79+ny*2};if(!nav.clear(a,b,.09))continue;seen.add(nk);component.push(nk);
 }}components.push(component);
}
components.sort((a,b)=>b.length-a.length);
let hash=2166136261;for(const c of JSON.stringify(geo))hash=Math.imul(hash^c.charCodeAt(0),16777619)>>>0;
fs.writeFileSync(new URL('../public/sea-access.js',import.meta.url),`// Generated by scripts/generate-sea-access.mjs; largest connected open-ocean component.\nexport const COASTLINE_HASH=${hash};\nexport const OCEAN_NODES=${JSON.stringify(components[0].sort((a,b)=>a-b))};\n`);
console.log({components:components.map(c=>c.length),hash});
